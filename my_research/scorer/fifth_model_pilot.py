"""Fifth-model pilot check: apply the selection rule (DECISIONS.md, "Fifth model").

  python3 my_research/scorer/fifth_model_pilot.py [aya llama2 ...]
      [--results my_research/results] [--out my_research/results/fifth_model]

The rule uses the neutral set only (<model>_ru.pkl, Gender_identity), never
`fem`. Rows: the 144 items of the `fem` study (the 17 templates; their
example_ids from the generated Gender_identity_ru_fem.jsonl) x 5 prompts =
360 ambiguous + 360 disambiguated. Re-detected with the current code, as in
fem_analysis.py. A candidate fails if any of:
  1. it doesn't run end to end by the date in DECISIONS.md (not checked here:
     this reports whether the pickle exists and is complete);
  2. more than MAX_UNDETECTED of the 720 answers are undetected;
  3. Acc_D (frozen scorer, published method: detected rows, mean over
     templates) is below MIN_ACC_D;
  4. more than MAX_UNKNOWN of the detected ambiguous answers are «unknown».
With no model names it checks every <model>_ru.pkl it finds, so the four
models already run show how the rule sorts known models.
Writes PILOT_CHECK.md to --out.
"""
import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import fem_analysis as F  # noqa: E402
from mbbq_scorer import annotate, score  # noqa: E402
from score_both_signs import Outputs  # noqa: E402

# Must equal DECISIONS.md, "Fifth model" (fixed before any candidate output is seen).
MAX_UNDETECTED = 0.05
MIN_ACC_D = 0.45
MAX_UNKNOWN = 0.80
CANDIDATES = ["aya", "llama2"]
KNOWN = ["mistral", "zephyr", "qwen", "tlite"]


def check(df, fem_items):
    gi = df[df["subset"] == "Gender_identity"]
    x = gi[gi["example_id"].isin(fem_items)]
    complete = (len(x) == 5 * len(fem_items)
                and not x.duplicated(F.KEY).any()
                and x.groupby("example_id")["prompt_id"].nunique().eq(5).all())
    amb = x[(x["context_condition"] == "ambig") & x["pick"].notna()]
    s = score(annotate(x))
    r = {"rows": len(x), "complete": bool(complete),
         "n ambig": int((x["context_condition"] == "ambig").sum()),
         "n disambig": int((x["context_condition"] == "disambig").sum()),
         "undetected": float(x["pick"].isna().mean()),
         "acc_D": float(s["acc_D"]), "acc_A": float(s["acc_A"]),
         "unknown share": float((amb["pick"] == "u").mean()),
         "all-rows Gender_identity": len(gi)}
    r["fails"] = [n for n, bad in [("2 undetected", r["undetected"] > MAX_UNDETECTED),
                                   ("3 Acc_D", r["acc_D"] < MIN_ACC_D),
                                   ("4 unknown", r["unknown share"] > MAX_UNKNOWN),
                                   ("incomplete", not complete)] if bad]
    return r


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("models", nargs="*")
    ap.add_argument("--results", default=ROOT / "my_research" / "results")
    ap.add_argument("--out", default=ROOT / "my_research" / "results" / "fifth_model")
    args = ap.parse_args()
    results = Path(args.results)
    models = args.models or [m for m in KNOWN + CANDIDATES if (results / f"{m}_ru.pkl").exists()]

    with tempfile.TemporaryDirectory() as tmp:
        data = Path(tmp)
        gen = subprocess.run([sys.executable, str(ROOT / "my_research/templates/generate_ru.py"),
                              "--out", str(data)],
                             capture_output=True, text=True)
        if gen.returncode:
            sys.exit(f"generate_ru.py failed:\n{gen.stdout}{gen.stderr}")
        fem_items = {json.loads(l)["example_id"]
                     for l in open(data / "Gender_identity_ru_fem.jsonl", encoding="utf-8")}
        genders = F.option_genders(data / "Gender_identity_ru.jsonl")
        out = Outputs(results, ROOT / "data", data)
        rows = {}
        for m in models:
            raw = out.get(m, "ru", "main")
            if raw is None:
                rows[m] = None
                continue
            raw = raw[raw["subset"] == "Gender_identity"]
            rows[m] = check(F.classify(raw, genders), fem_items)

    L = ["# Fifth-model pilot check", "",
         "Generated by `my_research/scorer/fifth_model_pilot.py`. Neutral set (`<model>_ru.pkl`),",
         f"Gender_identity, the {len(fem_items)} items of the fem study × 5 prompts, re-detected.",
         f"Fails if undetected > {MAX_UNDETECTED:.0%}, Acc_D < {MIN_ACC_D:.0%} or «unknown» > "
         f"{MAX_UNKNOWN:.0%} of detected ambiguous answers (DECISIONS.md, \"Fifth model\").",
         "Criterion 1 (runs end to end by the deadline) is checked by hand.", "",
         "| Model | Role | Rows (ambig / disambig) | Complete | Undetected | Acc_D | «Unknown» share "
         "(ambig) | Acc_A | Verdict |", "|---|---|---|---|---|---|---|---|---|"]
    for m, r in rows.items():
        role = "candidate" if m in CANDIDATES else "already run (reference)"
        if r is None:
            L.append(f"| {m} | {role} | no `{m}_ru.pkl` | | | | | | not run |")
            continue
        verdict = "passes" if not r["fails"] else "fails: " + ", ".join(r["fails"])
        L.append(f"| {m} | {role} | {r['n ambig']} / {r['n disambig']} | "
                 f"{'yes' if r['complete'] else 'no'} | {r['undetected']:.2%} | {r['acc_D']:.3f} | "
                 f"{r['unknown share']:.3f} | {r['acc_A']:.3f} | {verdict} |")
    L += ["", "## Notes", ""]
    L += [f"- Re-detected `{n}`: undetected {x} → {y}, {c} rows changed"
          for n, x, y, c in out.redetected]
    if out.missing:
        L.append("- Missing: " + ", ".join(f"`{m}`" for m in out.missing))
    Path(args.out).mkdir(parents=True, exist_ok=True)
    (Path(args.out) / "PILOT_CHECK.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

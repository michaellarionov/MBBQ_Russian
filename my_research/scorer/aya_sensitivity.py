"""Aya-101: the fem/masc tests under three readings of a lone Cyrillic «В».

  python3 my_research/scorer/aya_sensitivity.py [--model aya] [--draws 10000]
      [--seed 3] [--results my_research/results] [--out my_research/results/fem]

Fixed before Aya's masc/fem runs (DECISIONS.md, "Fifth model", amendment
2026-11-10). Aya often answers «(В).» or «В.», which the detection leaves
undetected (Latin B or the third Cyrillic letter?). Readings:
  - as detected: a lone «В» stays undetected (the primary analysis);
  - «В» as C, and «В» as B: every undetected answer that is exactly «(В).»
    or «В.» is recoded; nothing else changes (fem_analysis.recode_lone_v).
Per reading, on the 144 fem items x 5 prompts, every set re-detected first:
  - undetected rate per set;
  - H1/H2: item-level sign tests as in fem_analysis.py, Holm over the two;
    template-level exact Wilcoxon as in fem_reviewer_checks.py;
  - the ambiguous directional shift (+1 man, -1 woman, 0 unknown) and the
    disambiguated accuracy change by gold gender, with template-cluster 95%
    bootstrap CIs, for fem vs. masc, masc vs. neutral and rerun vs. masc.
A hypothesis counts as robust only if it is in the predicted direction with
Holm p < 0.05 under all three readings.
Writes AYA_SENSITIVITY.md to --out.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import fem_analysis as F  # noqa: E402
from fem_reviewer_checks import exact_wilcoxon  # noqa: E402
from score_both_signs import Outputs  # noqa: E402

SETS = ["main", "masc", "fem", "masc_rerun", "masc_batch"]
LABEL = {"main": "neutral", "masc": "masc", "fem": "fem", "masc_rerun": "rerun",
         "masc_batch": "batch"}
# «В» as C is the settled, primary reading (DECISIONS.md, amendment "settling the
# «В» reading": 26 lone «Б», 0 lone Cyrillic «С»); the other two are sensitivity.
READINGS = [("as detected", None), ("«В» as C", 2), ("«В» as B", 1)]
PRIMARY = "«В» as C"
COMPARISONS = [("fem", "masc"), ("masc", "main"), ("masc_rerun", "masc")]


def boot(x, rng, draws):
    """mean(d) x 100 and its template-cluster percentile 95% CI."""
    t = x.groupby("q_id_a")["d"].agg(["sum", "count"])
    s, c = t["sum"].to_numpy(float), t["count"].to_numpy(float)
    idx = rng.integers(0, len(t), size=(draws, len(t)))
    bs = s[idx].sum(axis=1) / c[idx].sum(axis=1)
    lo, hi = np.percentile(bs, [2.5, 97.5]) * 100
    return x["d"].mean() * 100, lo, hi


def pair(a, b, cond):
    m = a.merge(b, on=F.KEY, suffixes=("_a", "_b"))
    return m[m["pick_a"].notna() & m["pick_b"].notna() & (m["context_condition_a"] == cond)].copy()


def fmt_ci(e, lo, hi):
    return f"{e:+.1f} [{lo:+.1f}, {hi:+.1f}]"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--model", default="aya")
    ap.add_argument("--results", default=ROOT / "my_research" / "results")
    ap.add_argument("--out", default=ROOT / "my_research" / "results" / "fem")
    ap.add_argument("--draws", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=3)
    args = ap.parse_args()
    m = args.model

    with tempfile.TemporaryDirectory() as tmp:
        data = Path(tmp)
        gen = subprocess.run([sys.executable, str(ROOT / "my_research/templates/generate_ru.py"),
                              "--out", str(data)], capture_output=True, text=True)
        if gen.returncode:
            sys.exit(f"generate_ru.py failed:\n{gen.stdout}{gen.stderr}")
        out = Outputs(args.results, ROOT / "data", data)
        raw = {s: out.get(m, "ru", s) for s in SETS}
        if any(v is None for v in raw.values()):
            sys.exit("missing: " + ", ".join(out.missing))
        genders = {s: F.option_genders(data / F.DATA_FILE[s]) for s in SETS}
        fem_items = set(raw["fem"].loc[raw["fem"]["subset"] == "Gender_identity", "example_id"])
        by_reading = {}
        for name, letter in READINGS:
            sets, recoded = {}, {}
            for s in SETS:
                d = raw[s][(raw[s]["subset"] == "Gender_identity")
                           & raw[s]["example_id"].isin(fem_items)]
                if letter is not None:
                    d, recoded[s] = F.recode_lone_v(d, letter)
                sets[s] = F.classify(d, genders[s])
            by_reading[name] = (sets, recoded)

    L = [f"# {m.capitalize()}: fem/masc tests under three readings of a lone «В»", "",
         "Generated by `my_research/scorer/aya_sensitivity.py`; analysis fixed before the runs",
         "(`DECISIONS.md`, \"Fifth model\", amendment 2026-11-10). Supplementary model: added",
         "after failing the fifth-model rule (19.31% undetected in the pilot). 144 fem items",
         f"× 5 prompts per set; bootstrap {args.draws:,} template-cluster draws, seed {args.seed}",
         "(the same draws for every reading).", "",
         f"**Primary reading: {PRIMARY}**, settled by the rule fixed before counting",
         "(`DECISIONS.md`, \"Fifth model\", amendment \"settling the «В» reading\"): Aya wrote",
         "26 lone «Б» and 0 lone Cyrillic «С», so it uses Cyrillic alphabet order (А, Б, В).",
         "The other two readings are sensitivity analyses.", ""]

    L += ["## Undetected rate per set", "",
          "| Reading | " + " | ".join(LABEL[s] for s in SETS) + " | fem − masc |",
          "|---|" + "---|" * (len(SETS) + 1)]
    for name, (sets, recoded) in by_reading.items():
        u = {s: sets[s]["pick"].isna().mean() for s in SETS}
        L.append(f"| {name} | " + " | ".join(f"{100 * u[s]:.2f}%" for s in SETS)
                 + f" | {100 * (u['fem'] - u['masc']):+.2f} pts |")
    rec = by_reading["«В» as C"][1]
    L += ["", "Lone «В» answers recoded per set: "
          + ", ".join(f"{LABEL[s]} {rec[s]}" for s in SETS) + ".", ""]

    L += ["## H1 and H2 (fem vs. masc, ambiguous)", "",
          "Item sign test as in `fem_analysis.py`, Holm over Aya's two tests; template-level",
          "exact Wilcoxon (zeros dropped) as in `fem_reviewer_checks.py`.", "",
          "| Reading | Hypothesis | Items fem>masc / fem<masc | Sign p | Holm p | "
          "Templates fem>masc / fem<masc | Wilcoxon p |", "|---|---|---|---|---|---|---|"]
    verdict = {"H1": [], "H2": []}
    for name, (sets, _) in by_reading.items():
        r = F.compare(sets["fem"], sets["masc"])
        amb = pair(sets["fem"], sets["masc"], "ambig")
        res = []
        for g, h in (("woman", "H1"), ("man", "H2")):
            x = r[g]
            col = "f" if g == "woman" else "m"
            d = (amb["pick_a"] == col).astype(int) - (amb["pick_b"] == col).astype(int)
            wp, _ = exact_wilcoxon(d.groupby([amb["subset"], amb["q_id_a"]]).mean().to_numpy())
            pred = x["items a>b"] > x["items a<b"] if h == "H1" else x["items a<b"] > x["items a>b"]
            res.append((h, x, wp, pred))
        for (h, x, wp, pred), q in zip(res, F.holm([t[1]["p sign test"] for t in res])):
            verdict[h].append(pred and q < 0.05)
            L.append(f"| {name} | {h} | {x['items a>b']} / {x['items a<b']} | "
                     f"{F.fmt_p(x['p sign test'])} | {F.fmt_p(q)} | "
                     f"{x['templates a>b']} / {x['templates a<b']} | {F.fmt_p(wp)} |")
    L.append("")
    for h, oks in verdict.items():
        state = ("**robust**: holds under all three readings" if all(oks) else
                 "not significant under any reading" if not any(oks) else
                 "**depends on how «В» is read**: holds under "
                 + ", ".join(n for (n, _), ok in zip(READINGS, oks) if ok))
        L.append(f"- {h}: {state}")

    L += ["", "## Shifts with 95% bootstrap CIs (points)", "",
          "Ambiguous: directional score, + toward the man. Disambiguated: change in accuracy",
          "under the first set, by the gold person's gender.", "",
          "| Reading | Comparison | Ambiguous shift | Disamb., gold woman | Disamb., gold man |",
          "|---|---|---|---|---|"]
    for name, (sets, _) in by_reading.items():
        rng = np.random.default_rng(args.seed)
        for a, b in COMPARISONS:
            amb = pair(sets[a], sets[b], "ambig")
            sc = lambda p: (p == "m").astype(int) - (p == "f").astype(int)  # noqa: E731
            amb["d"] = sc(amb["pick_a"]) - sc(amb["pick_b"])
            cells = [fmt_ci(*boot(amb, rng, args.draws))]
            dis = pair(sets[a], sets[b], "disambig")
            for g in ("f", "m"):
                y = dis[dis["gold_gender_a"] == g].copy()
                y["d"] = (y["pick_a"] == g).astype(int) - (y["pick_b"] == g).astype(int)
                cells.append(fmt_ci(*boot(y, rng, args.draws)))
            L.append(f"| {name} | {LABEL[a]} vs. {LABEL[b]} | " + " | ".join(cells) + " |")
    L += ["", "## Notes", ""]
    L += [f"- Re-detected `{n}`: undetected {x} → {y}, {c} rows changed"
          for n, x, y, c in out.redetected]

    Path(args.out).mkdir(parents=True, exist_ok=True)
    (Path(args.out) / "AYA_SENSITIVITY.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
